// Operadores Aritméticos
let a = 10
let b = 3

console.log(a+b) // Soma
console.log(a-b) // Subtração
console.log(10*3) // Multiplicação
console.log(a/b) // Divisão
console.lob(2%2) // Resto da divisão

// Operadores de Comparação
let x = 5
let y = "5"

console.log(x == y) // Verificam apenas se o valor é igual
console.log(x === y) // Verificam se o valor e o tipo são iguais

console.log(x != y) // Verificam se o valor são diferente
console.log(x !== y) // Verificam se o valor e o tipo são diferentes

console.log(10 > 3) // Verifica se o primeiro valor é maior que o segundo
console.log(10 < 3) // Verifica se o primeiro valor é menor que o segundo
console.log(10 >= 3) // Verifica se o primeiro valor é maior ou igual ao segundo
console.log(10 <= 3) // Verifica se o primeiro valor é menor ou igual ao segundo

// Operadores Lógicos
let idade = 20
let temCNH = true

console.log(idade >= 18 && temCNH == true) // Operador logico "and" &&
console.log(idade >= 18 || temCNH == false) // Operador logico "or" ||
console.log(!(idade > 18)) // Operador logico "not" !

